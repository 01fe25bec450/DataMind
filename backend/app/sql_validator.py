"""
DataMind Server-Side SQL Validator
ZeroDay OSS Hacktoberfest 2026 - Stage 3

This module provides independent, server-side AST-based SQL validation for
Gemma-generated queries using sqlglot (Snowflake dialect).

SECURITY DESIGN & SAFEGUARDS:
  1. Single Statement Enforcement: Exactly one statement is allowed. Multi-statement
     injection attempts (e.g. `SELECT 1; DROP TABLE users;`) are strictly rejected.
  2. Read-Only AST Validation: The statement must be an exp.Select or exp.Union.
     Any presence of data-changing or DDL expressions (Insert, Update, Delete,
     Drop, Alter, Truncate, Create, Merge, Grant, Revoke, etc.) is rejected.
  3. Schema Table Conformance: All referenced tables (excluding CTE aliases)
     are checked against allowed schema metadata when available.
  4. Automatic Row Limiting: If the query does not specify a LIMIT or exceeds
     max_row_limit, a safe LIMIT is enforced to prevent runaway queries.
  5. Comments & Obfuscation Defense: sqlglot parses queries into an Abstract Syntax
     Tree (AST), neutralising comment-based smuggling (-- or /* */) or whitespace obfuscation.
  6. Fail-Closed Policy: Any parsing failure or unrecognized construct causes immediate
     rejection.

LIMITATIONS OF STATIC SQL VALIDATION:
  - Stored Procedures & UDFs: Static AST checks do not execute or analyze the internal logic
    of stored procedures or arbitrary UDFs. Therefore, CALL statements are explicitly disallowed.
  - Runtime Permissions: Static parsing verifies syntax and table references, but Snowflake
    role permissions and row/column masking policies must still be enforced via least-privilege
    Snowflake roles.
  - Computational Complexity: Valid SELECT queries can still be computationally expensive (e.g.
    Cartesian joins). This is mitigated by Snowflake execution timeouts and row limits.
"""

from typing import List, Optional, Set, Tuple
import sqlglot
from sqlglot import exp
from sqlglot.errors import ParseError

# Disallowed AST expression types that modify data, structure, or permissions
DISALLOWED_EXPRESSION_TYPES = (
    exp.Insert,
    exp.Update,
    exp.Delete,
    exp.Drop,
    exp.Alter,
    exp.Create,
    exp.TruncateTable,
    exp.Merge,
    exp.Command,
    exp.Transaction,
    exp.Commit,
    exp.Rollback,
    exp.Set,
)


def validate_and_normalize_sql(
    raw_sql: str,
    allowed_tables: Optional[List[str]] = None,
    max_row_limit: int = 100,
) -> Tuple[bool, str, Optional[str]]:
    """
    Validate and normalize a Snowflake SQL query.

    Args:
        raw_sql: The raw SQL string generated by Gemma or submitted by user.
        allowed_tables: Optional list of authorized table names (case-insensitive).
        max_row_limit: Maximum allowed row limit (default: 100).

    Returns:
        Tuple of:
          - is_valid (bool): True if SQL passed all safety checks.
          - message (str): Success explanation or reason for rejection.
          - normalized_sql (Optional[str]): Safe, normalized Snowflake SQL string.
    """
    if not raw_sql or not raw_sql.strip():
        return False, "SQL query cannot be empty.", None

    # Step 1: Parse the SQL into AST nodes using Snowflake dialect
    try:
        parsed_expressions = sqlglot.parse(raw_sql.strip(), read="snowflake")
    except ParseError as parse_err:
        return False, f"SQL syntax parsing failed: {str(parse_err)}", None
    except Exception as exc:
        return False, f"Unexpected SQL parser error: {str(exc)}", None

    # Filter out empty or semicolon-only tokens
    statements = [
        s for s in parsed_expressions
        if s is not None and not isinstance(s, exp.Semicolon)
    ]

    # Step 2: Accept exactly one statement
    if len(statements) == 0:
        return False, "No valid SQL statement found.", None
    if len(statements) > 1:
        return (
            False,
            f"Multiple SQL statements detected ({len(statements)}). Only exactly one statement is permitted.",
            None,
        )

    stmt = statements[0]

    # Step 3: Verify the top-level statement is a read-only query (Select or Union)
    if not isinstance(stmt, (exp.Select, exp.Union)):
        return (
            False,
            f"Disallowed statement type: {type(stmt).__name__}. Only read-only SELECT queries are allowed.",
            None,
        )

    # Step 4: Inspect all sub-nodes in the AST for disallowed operations
    for node in stmt.walk():
        if isinstance(node, DISALLOWED_EXPRESSION_TYPES):
            return (
                False,
                f"Disallowed operation detected: {type(node).__name__}. Data modifications and DDL are prohibited.",
                None,
            )

    # Step 5: Check table references against allowed schema metadata
    cte_names: Set[str] = set()
    if hasattr(stmt, "ctes") and stmt.ctes:
        for cte in stmt.ctes:
            if cte.alias_or_name:
                cte_names.add(cte.alias_or_name.upper())

    referenced_tables: Set[str] = set()
    for table_node in stmt.find_all(exp.Table):
        if table_node.name:
            t_name = table_node.name.upper()
            # If not a locally defined CTE, track as external table
            if t_name not in cte_names:
                referenced_tables.add(t_name)

    if allowed_tables:
        allowed_upper = {t.upper() for t in allowed_tables}
        # Check for unapproved external tables
        unauthorized_tables = [
            t for t in referenced_tables
            if t not in allowed_upper
        ]
        if unauthorized_tables:
            return (
                False,
                f"Query references unapproved table(s): {', '.join(unauthorized_tables)}. "
                f"Allowed tables: {', '.join(sorted(allowed_upper))}.",
                None,
            )

    # Step 6: Safe Row Limit Enforcement
    # Check if a LIMIT clause exists on the outer query
    limit_node = stmt.args.get("limit")
    if limit_node is None:
        # Append limit clause to outer query
        stmt = stmt.limit(max_row_limit)
    else:
        # Check if limit expression exceeds max_row_limit
        try:
            val = int(limit_node.expression.this)
            if val > max_row_limit or val <= 0:
                stmt = stmt.limit(max_row_limit)
        except (ValueError, TypeError, AttributeError):
            stmt = stmt.limit(max_row_limit)

    # Step 7: Transpile / Format back to safe Snowflake SQL
    try:
        normalized_sql = stmt.sql(dialect="snowflake", pretty=True)
        return True, "SQL validation passed successfully.", normalized_sql
    except Exception as exc:
        return False, f"Failed to generate normalized Snowflake SQL: {str(exc)}", None
